@router.post(
    "",
    response_model=ChatResponse,
    status_code=status.HTTP_200_OK,
    summary="Send a question to the dual-mode RAG chatbot",
    description=(
        "Accepts a natural-language question and an optional session_id.  "
        "The agent router classifies the query (rag | sql | hybrid), executes "
        "the appropriate retrieval pipeline, and returns a structured JSON response."
    ),
    responses={
        400: {"model": ErrorResponse, "description": "Bad request — blank or invalid question."},
        422: {"description": "Validation error — request body does not match schema."},
        500: {"model": ErrorResponse, "description": "Internal server error — workflow failure."},
    },
)
async def chat(request: ChatRequest) -> ChatResponse:
    """
    Standard chat endpoint.

    Workflow:
    1. Resolve / create session_id.
    2. Load conversation history from memory store.
    3. Build initial LangGraph state.
    4. Invoke the compiled workflow asynchronously.
    5. Persist the new turn (question + answer) to memory.
    6. Return a structured ChatResponse.
    """
    request_id = str(uuid.uuid4())
    wall_start = time.perf_counter()

    # Resolve session
    session_id = request.session_id or str(uuid.uuid4())
    session_id_var.set(session_id)

    logger.info(
        "[Chat API] request_id=%s session_id=%s question='%s'",
        request_id,
        session_id,
        request.question[:120],
    )

    # Load memory
    conversation_history = ""
    if settings.ENABLE_MEMORY:
        try:
            conversation_history = memory_store.get_history(session_id)
        except Exception as mem_exc:
            logger.warning("[Chat API] Memory load failed: %s", mem_exc)

    # Build state and invoke graph
    initial_state = _build_initial_state(
        question=request.question,
        conversation_history=conversation_history,
        stream_queue=None,
    )

    try:
        result: AgentState = await agent_workflow.ainvoke(initial_state)
    except GuardrailException as exc:
        logger.warning("[Chat API] Guardrail violation | request_id=%s | error=%s", request_id, exc)
        ERRORS_TOTAL.labels(component="workflow", error_type=type(exc).__name__).inc()
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(exc),
        )
    except OutputValidationException as exc:
        logger.warning("[Chat API] Output validation violation | request_id=%s | error=%s", request_id, exc)
        ERRORS_TOTAL.labels(component="workflow", error_type=type(exc).__name__).inc()
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=str(exc),
        )
    except Exception as exc:
        logger.exception(
            "[Chat API] Workflow error | request_id=%s | error=%s", request_id, exc
        )
        ERRORS_TOTAL.labels(component="workflow", error_type=type(exc).__name__).inc()
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=str(exc),
        )

    # Emit Prometheus workflow metrics
    record_workflow_metrics(
        execution_metrics=result.get("execution_metrics", {}),
        route=result.get("route", "unknown"),
    )

    # Persist turn to memory
    if settings.ENABLE_MEMORY:
        try:
            memory_store.add_message(session_id, "human", request.question)
            memory_store.add_message(session_id, "assistant", result.get("final_answer", ""))
        except Exception as mem_exc:
            logger.warning("[Chat API] Memory save failed: %s", mem_exc)

    wall_ms = (time.perf_counter() - wall_start) * 1000
    logger.info(
        "[Chat API] request_id=%s | route=%s | confidence=%.2f | total_wall_ms=%.1f",
        request_id,
        result.get("route", "unknown"),
        result.get("confidence", 0.0),
        wall_ms,
    )

    return ChatResponse(
        request_id=request_id,
        session_id=session_id,
        answer=result.get("final_answer", ""),
        route=result.get("route", ""),
        confidence=result.get("confidence", 0.0),
        execution_metrics=_metrics_from_dict(result.get("execution_metrics", {})),
        sources=_extract_sources(result.get("rag_context", "")),
        sql_query=result.get("sql_query", ""),
        sql_result=_parse_sql_result(result.get("sql_result", "")),
    )


# ---------------------------------------------------------------------------
# POST /chat/stream — Server-Sent Events streaming endpoint
# ---------------------------------------------------------------------------


async def _sse_event(data: str) -> str:
    """Encode a string as a well-formed SSE ``data:`` line."""
    # Escape embedded newlines so they don't break the SSE framing.
    payload = data.replace("\n", "\\n")
    return f"data: {payload}\n\n"


async def _token_generator(
    question: str,
    session_id: str,
    conversation_history: str,
    request_id: str,
) -> AsyncGenerator[str, None]:
    """
    Run the LangGraph workflow with a stream_queue and yield SSE events.

    The answer_node places token strings into the queue and signals completion
    with a ``None`` sentinel.  A separate asyncio.Task runs the full workflow
    so the queue reader and the graph run concurrently on the same event loop.

    If the LLM or the workflow raises an exception the error is surfaced as a
    JSON-encoded SSE ``error`` event before the stream closes.
    """
    queue: asyncio.Queue[Optional[str]] = asyncio.Queue()

    initial_state = _build_initial_state(
        question=question,
        conversation_history=conversation_history,
        stream_queue=queue,
    )

    # Run the workflow as a background task
    workflow_task: asyncio.Task = asyncio.create_task(
        agent_workflow.ainvoke(initial_state)
    )

    final_result: Optional[AgentState] = None
    full_answer_parts: List[str] = []

    try:
        while True:
            if workflow_task.done():
                if workflow_task.exception():
                    raise workflow_task.exception()
            
            try:
                # Wait for the next token
                token: Optional[str] = await asyncio.wait_for(
                    queue.get(), timeout=1.0
                )
            except asyncio.TimeoutError:
                if workflow_task.done():
                    continue
                # If we've waited longer than LLM_TIMEOUT in total, we could timeout here,
                # but for simplicity and responsiveness we just continue and check workflow_task
                continue

            if token is None:
                # Sentinel: stream complete
                break

            full_answer_parts.append(token)
            yield await _sse_event(json.dumps({"token": token}))

        # Await the workflow task to retrieve full state for metadata
        try:
            final_result = await workflow_task
        except Exception as task_exc:
            logger.error("[Chat Stream] Workflow task error: %s", task_exc)

    except asyncio.CancelledError:
        workflow_task.cancel()
        raise

    except GuardrailException as exc:
        logger.warning("[Chat Stream] Guardrail violation | request_id=%s | error=%s", request_id, exc)
        yield await _sse_event(json.dumps({"error": str(exc), "code": 400}))
        workflow_task.cancel()
        return
    except OutputValidationException as exc:
        logger.warning("[Chat Stream] Output validation violation | request_id=%s | error=%s", request_id, exc)
        yield await _sse_event(json.dumps({"error": str(exc), "code": 422}))
        workflow_task.cancel()
        return
    except Exception as exc:
        logger.exception("[Chat Stream] Generator error | request_id=%s | %s", request_id, exc)
        yield await _sse_event(json.dumps({"error": str(exc), "code": 500}))
        workflow_task.cancel()
        return

    # Emit final metadata event
    if final_result:
        metadata = {
            "done": True,
            "route": final_result.get("route", ""),
            "confidence": final_result.get("confidence", 0.0),
            "session_id": session_id,
            "request_id": request_id,
            "sources": _extract_sources(final_result.get("rag_context", "")),
            "sql_query": final_result.get("sql_query", ""),
            "sql_result": _parse_sql_result(final_result.get("sql_result", "")),
            "execution_metrics": final_result.get("execution_metrics", {}),
        }
        yield await _sse_event(json.dumps(metadata))

        # Persist turn to memory after stream completes
        if settings.ENABLE_MEMORY:
            full_answer = "".join(full_answer_parts)
            try:
                memory_store.add_message(session_id, "human", question)
                memory_store.add_message(session_id, "assistant", full_answer)
            except Exception as mem_exc:
                logger.warning("[Chat Stream] Memory save failed: %s", mem_exc)

    yield "data: [DONE]\n\n"


@router.post(
    "/stream",
    summary="Stream the chatbot response token-by-token via SSE",
    description=(
        "Identical to POST /chat but returns a ``text/event-stream`` response "
        "where each token is emitted as a Server-Sent Event.  A final event "
        "with ``done=true`` carries route, confidence, sources, and metrics. "
        "Falls back to a single-chunk response if the LLM does not support streaming."
    ),
    response_class=StreamingResponse,
    responses={
        200: {"description": "Server-Sent Events stream (text/event-stream)."},
        400: {"model": ErrorResponse, "description": "Bad request."},
        422: {"description": "Validation error."},
        500: {"model": ErrorResponse, "description": "Workflow error."},
    },
)
async def chat_stream(request: ChatRequest) -> StreamingResponse:
    """
    Streaming chat endpoint using Server-Sent Events.

    Clients should consume the ``data:`` lines and parse each JSON payload.
    The stream ends with the literal ``data: [DONE]`` sentinel line.
    """
    request_id = str(uuid.uuid4())
    session_id = request.session_id or str(uuid.uuid4())
    session_id_var.set(session_id)

    logger.info(
        "[Chat Stream] request_id=%s session_id=%s question='%s'",
        request_id,
        session_id,
        request.question[:120],
    )

    # Load memory before entering the generator
    conversation_history = ""
    if settings.ENABLE_MEMORY:
        try:
            conversation_history = memory_store.get_history(session_id)
        except Exception as mem_exc:
            logger.warning("[Chat Stream] Memory load failed: %s", mem_exc)

    return StreamingResponse(
        _token_generator(
            question=request.question,
            session_id=session_id,
            conversation_history=conversation_history,
            request_id=request_id,
        ),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "X-Accel-Buffering": "no",
            "Connection": "keep-alive",
            "X-Request-ID": request_id,
        },
    )
