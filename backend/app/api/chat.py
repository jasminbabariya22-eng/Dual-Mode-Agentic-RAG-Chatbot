"""
Chat API Router.

Exposes the LangGraph dual-mode agentic RAG workflow via two FastAPI endpoints:

    POST /chat         — Standard JSON request / response.
    POST /chat/stream  — Server-Sent Events (SSE) token stream.

Design decisions:
- All heavy orchestration lives in the workflow; this module is *only* an adapter.
- Session memory is injected into the initial graph state so history reaches the
  answer node without polluting the router, retriever, or SQL engine nodes.
- A unique request_id (UUID4) is attached to every request for distributed tracing.
- Streaming uses asyncio.Queue to bridge the synchronous LangGraph run and the
  async SSE generator.  If the LLM does not support streaming, the workflow falls
  back to ainvoke automatically (see workflow.py answer_node).
- All exceptions are caught at the router level and translated to structured JSON
  error responses with appropriate HTTP status codes.
"""

import asyncio
import json
import time
import uuid
from typing import Any, AsyncGenerator, Dict, List, Optional

from fastapi import APIRouter, HTTPException, Request, status
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field, field_validator

from backend.app.agent.workflow import AgentState, agent_workflow
from backend.app.config import settings
from backend.app.core.logger import logger
from backend.app.memory.memory import memory_store
from backend.app.monitoring.metrics import ERRORS_TOTAL, record_workflow_metrics
from backend.app.core.guardrails import GuardrailException, OutputValidationException
from backend.app.core.logger import logger, session_id_var

# ---------------------------------------------------------------------------
# Router
# ---------------------------------------------------------------------------

router = APIRouter(prefix="/chat", tags=["Chat"])

# ---------------------------------------------------------------------------
# Request / Response Pydantic models
# ---------------------------------------------------------------------------


class ChatRequest(BaseModel):
    """
    Payload for POST /chat and POST /chat/stream.

    Attributes:
        question:   The user's natural-language question. Must be non-empty.
        session_id: Optional identifier used to load / persist conversation
                    history.  A new UUID is generated automatically when omitted.
    """

    question: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="The user's natural-language question (1–2000 characters).",
        examples=["What is the laptop warranty period?"],
    )
    session_id: Optional[str] = Field(
        default=None,
        description="Optional session identifier for conversation memory. "
        "A new session is created automatically when omitted.",
        examples=["user-abc-123"],
    )

    @field_validator("question")
    @classmethod
    def question_not_blank(cls, v: str) -> str:
        if not v.strip():
            raise ValueError("question must not be blank or whitespace-only.")
        return v.strip()


class ExecutionMetrics(BaseModel):
    """Latency breakdown for each pipeline stage (milliseconds)."""

    router_time_ms: float = 0.0
    retrieval_time_ms: float = 0.0
    sql_generation_time_ms: float = 0.0
    sql_execution_time_ms: float = 0.0
    answer_generation_time_ms: float = 0.0
    total_execution_time_ms: float = 0.0


class ChatResponse(BaseModel):
    """
    Structured response returned by POST /chat.

    All fields are always present; optional data uses empty string / empty list
    defaults so callers never need to handle ``None``.
    """

    request_id: str = Field(description="Unique identifier for this request (UUID4).")
    session_id: str = Field(description="Session identifier used for memory look-up.")
    answer: str = Field(description="Final markdown-formatted answer from the chatbot.")
    route: str = Field(description="Execution path chosen: rag | sql | hybrid.")
    confidence: float = Field(description="Router confidence score (0.0 – 1.0).")
    execution_metrics: ExecutionMetrics = Field(
        description="Per-stage latency breakdown in milliseconds."
    )
    sources: List[str] = Field(
        default_factory=list,
        description="Document chunk citations extracted from the RAG context.",
    )
    sql_query: str = Field(
        default="", description="The SQL query generated by the Text-to-SQL engine."
    )
    sql_result: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Rows returned by the SQL query execution.",
    )


class ErrorResponse(BaseModel):
    """Structured error envelope returned on 4xx / 5xx responses."""

    request_id: str
    error: str
    detail: str


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------


def _extract_sources(rag_context: str) -> List[str]:
    """
    Parse source citation lines from the RAG context string.

    The workflow formats context as::

        Document chunk:
        <text>
        Source: <citation>

    This helper collects all ``Source:`` lines and de-duplicates them while
    preserving insertion order.
    """
    seen: dict[str, None] = {}
    for line in rag_context.splitlines():
        stripped = line.strip()
        if stripped.startswith("Source:"):
            citation = stripped[len("Source:"):].strip()
            if citation:
                seen[citation] = None
    return list(seen.keys())


def _parse_sql_result(sql_result_raw: Any) -> List[Dict[str, Any]]:
    """
    Attempt to deserialise the SQL result string produced by the workflow.

    The workflow serialises results as a JSON array.  On error or empty result
    an empty list is returned so the API response is always valid.
    """
    if isinstance(sql_result_raw, list):
        return sql_result_raw
    if isinstance(sql_result_raw, dict):
        return [sql_result_raw]
    
    if not isinstance(sql_result_raw, str):
        return []
        
    sql_result_str = sql_result_raw
    if not sql_result_str or sql_result_str.startswith("Error:") or sql_result_str.startswith("Exception:"):
        return []
    try:
        parsed = json.loads(sql_result_str)
        if isinstance(parsed, list):
            return parsed
        if isinstance(parsed, dict):
            return [parsed]
        return []
    except (json.JSONDecodeError, ValueError):
        return []


def _build_initial_state(
    question: str,
    conversation_history: str,
    stream_queue: Optional[asyncio.Queue],
) -> AgentState:
    """Construct the initial AgentState dict fed to the compiled LangGraph graph."""
    return AgentState(
        question=question,
        route="",
        rag_context="",
        sql_query="",
        sql_result="",
        final_answer="",
        confidence=0.0,
        execution_metrics={},
        conversation_history=conversation_history,
        stream_queue=stream_queue,
    )


def _metrics_from_dict(raw: dict) -> ExecutionMetrics:
    """Safely build an ExecutionMetrics model from the raw workflow dict."""
    return ExecutionMetrics(
        router_time_ms=raw.get("router_time_ms", 0.0),
        retrieval_time_ms=raw.get("retrieval_time_ms", 0.0),
        sql_generation_time_ms=raw.get("sql_generation_time_ms", 0.0),
        sql_execution_time_ms=raw.get("sql_execution_time_ms", 0.0),
        answer_generation_time_ms=raw.get("answer_generation_time_ms", 0.0),
        total_execution_time_ms=raw.get("total_execution_time_ms", 0.0),
    )


